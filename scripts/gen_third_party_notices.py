"""Write the third-party notices for the parts that are not npm projects:

  mobile/android/pdfstudio/src/main/assets/pdfstudio/THIRD-PARTY-NOTICES.txt   (packed into every app that uses the AAR)
  mobile/ios/PDFStudioKit/THIRD-PARTY-NOTICES.txt
  server/THIRD-PARTY-NOTICES.txt                                               (Python packages + programs in the Docker image)

The web app's notices are written at build time by web/scripts/third-party-notices.mjs.

Run from the pdf-studio folder with the SERVER's Python (it reads the installed packages' licence files):
    server/.venv/bin/python scripts/gen_third_party_notices.py
Licence texts that aren't in any package are kept in scripts/licenses/.
"""
from __future__ import annotations

import re
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIC = Path(__file__).resolve().parent / "licenses"
LINE = "=" * 78
APACHE = (LIC / "Apache-2.0.txt").read_text(encoding="utf-8").strip()
OFL = (LIC / "OFL-1.1.txt").read_text(encoding="utf-8").strip()


def header(product: str, names: list[str]) -> list[str]:
    return [f"THIRD-PARTY SOFTWARE NOTICES for {product}", "",
            "This product includes the open-source software listed below, each used under its own licence.",
            "Generated by scripts/gen_third_party_notices.py; do not edit by hand.", "",
            *[f"  {n}" for n in names], ""]


def android() -> None:
    # Versions as declared in mobile/android/pdfstudio/build.gradle.kts
    gradle = (ROOT / "mobile/android/pdfstudio/build.gradle.kts").read_text(encoding="utf-8")
    ver = lambda coord: (re.search(re.escape(coord) + r":([\w.\-]+)\"", gradle) or re.search(r"(?!)", "")) and re.search(re.escape(coord) + r":([\w.\-]+)\"", gradle).group(1)
    comps = [
        (f"PdfBox-Android {ver('com.tom-roush:pdfbox-android')}", "Apache-2.0",
         "Port of Apache PDFBox to Android by Tom Roush and contributors. https://github.com/TomRoush/PdfBox-Android",
         (LIC / "PdfBox-Android-NOTICE.txt").read_text(encoding="utf-8").strip()),
        ("Liberation Sans 2.1.5 (font bundled inside PdfBox-Android)", "SIL Open Font License 1.1",
         "Digitized data copyright (c) 2010 Google Corporation.\nCopyright (c) 2012 Red Hat, Inc.", None),
        (f"kotlinx.serialization {ver('org.jetbrains.kotlinx:kotlinx-serialization-json')}", "Apache-2.0",
         "Copyright JetBrains s.r.o. and the kotlinx.serialization contributors. https://github.com/Kotlin/kotlinx.serialization", None),
        ("AndroidX libraries and Jetpack Compose (core-ktx, activity-compose, compose-ui, foundation, material3)", "Apache-2.0",
         "Copyright The Android Open Source Project. https://developer.android.com/jetpack/androidx", None),
    ]
    parts = header("the PDF Studio Android library (pdfstudio)", [f"{c[0]}  ({c[1]})" for c in comps])
    for name, lic, notice, extra in comps:
        parts += [LINE, name, f"Licence: {lic}", "", notice, ""]
        if extra:
            parts += ["NOTICE:", extra, ""]
    parts += [LINE, "Apache License 2.0 (applies to the Apache-2.0 components above)", "", APACHE, "",
              LINE, "SIL Open Font License 1.1 (applies to Liberation Sans)", "", OFL, ""]
    out = ROOT / "mobile/android/pdfstudio/src/main/assets/pdfstudio/THIRD-PARTY-NOTICES.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"android: {len(comps)} components → {out.relative_to(ROOT)}")


def ios() -> None:
    text = "\n".join(header("PDFStudioKit (iOS)", ["(none)"]) + [
        "PDFStudioKit uses only Apple system frameworks (PDFKit, SwiftUI, UIKit, CoreGraphics, Foundation).",
        "It contains no third-party code, fonts or other assets, so it adds no third-party notices to an app.", ""])
    out = ROOT / "mobile/ios/PDFStudioKit/THIRD-PARTY-NOTICES.txt"
    out.write_text(text, encoding="utf-8")
    print(f"ios: no third-party components → {out.relative_to(ROOT)}")


def server() -> None:
    reqs = (ROOT / "server/requirements.txt").read_text(encoding="utf-8")
    top = [re.split(r"[=<>\[ ]", ln.strip())[0] for ln in reqs.splitlines() if ln.strip() and not ln.startswith("#")]
    seen: dict[str, tuple] = {}

    def walk(req: str) -> None:
        name = re.split(r"[ ;<>=\[!~(]", req.strip())[0]
        key = re.sub(r"[-_.]+", "-", name).lower()
        if not name or key in seen:
            return
        try:
            d = distribution(name)
        except PackageNotFoundError:
            return
        m = d.metadata
        classifiers = "; ".join(c.split("::")[-1].strip() for c in (m.get_all("Classifier") or []) if c.startswith("License ::"))
        free_text = (m.get("License") or "").strip().splitlines()
        lic = m.get("License-Expression") or classifiers or (free_text[0][:80] if free_text else "")
        # licence files: LICENSE / COPYING / NOTICE anywhere, plus everything under dist-info/licenses/ (PEP 639)
        texts = [f"[{f}]\n{f.locate().read_text(encoding='utf-8', errors='replace')}" for f in (d.files or [])
                 if f.suffix not in (".py", ".pyc", ".so", ".dylib")
                 and (re.search(r"(LICEN[CS]E|COPYING|NOTICE)[^/]*$", f.name, re.I) or "/licenses/" in str(f).replace("\\", "/"))]
        seen[key] = (m["Name"], d.version, lic or "see licence text", [t.strip() for t in texts if t])
        for r in d.requires or []:
            if "extra ==" not in r:
                walk(r)

    for t in top:
        walk(t)
    pkgs = sorted(seen.values(), key=lambda p: p[0].lower())
    missing = [p[0] for p in pkgs if not p[3]]
    programs = [
        ("LibreOffice", "MPL-2.0 (and others; see /usr/share/doc/libreoffice*/copyright in the image)", "Separate program, run with soffice --headless."),
        ("Tesseract OCR and its language data", "Apache-2.0", "Separate program."),
        ("Noto fonts, DejaVu fonts, Liberation fonts", "SIL OFL 1.1 / Bitstream Vera licence", "Installed from Debian packages; licences in /usr/share/doc/*/copyright in the image."),
        ("Debian base image and Python 3.12", "Various (Debian Free Software Guidelines); PSF-2.0", "Licences in /usr/share/doc in the image."),
    ]
    parts = header("the PDF Studio server", [f"{n} {v}  ({l})" for n, v, l, _ in pkgs] + ["", "Programs in the Docker image:"] + [f"{n}  ({l})" for n, l, _ in programs])
    for n, v, lic, texts in pkgs:
        parts += [LINE, f"{n} {v}", f"Licence: {lic}", ""]
        parts += [t + "\n" for t in texts] if texts else ["(no licence file shipped in the package; licence as stated above)", ""]
    parts += [LINE, "Programs in the Docker image", ""] + [f"{n}: {l}. {how}" for n, l, how in programs] + [""]
    out = ROOT / "server/THIRD-PARTY-NOTICES.txt"
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"server: {len(pkgs)} packages → {out.relative_to(ROOT)}" + (f"; no licence file in: {', '.join(missing)}" if missing else ""))


if __name__ == "__main__":
    android()
    ios()
    server()
